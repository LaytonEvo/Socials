"""Task 3.11 — signing a finished render with a C2PA manifest.

**What this is for, and what it is not.** A C2PA manifest is a signed, tamper-evident
record embedded in the file: what made it, when, and that it was generated by a model.
Amendment A9 sized it correctly and nothing here changes that — most platforms re-encode
on upload and strip the manifest, so **this is provenance for us, not a disclosure signal
the audience sees.** The burned-in overlay (3.10) and the platform label (7.2) do the
disclosure work. Keep the requirement; do not over-invest in it.

**Disclosure first, by construction.** `sign` takes a `FinalRender`, which only
`apply_disclosure` can produce. So a signed file has necessarily been through the overlay
pass, and the database's `c2pa_manifest_key IS NULL OR disclosure_applied` check can never
be the thing that catches a mistake — it will already be impossible to make one.

**The manifest always says the content is AI-generated.** `digitalSourceType` is pinned to
IPTC `trainedAlgorithmicMedia` with no parameter to vary it, because CLAUDE.md forbids a
flag, env var or code path that skips the disclosure, and a manifest that omitted it would
be exactly that with extra steps.

**Trust is a separate thing from validity.** A manifest signed with our own certificate
verifies as *valid* — the bytes have not been altered since signing — but not as *trusted*,
which needs a certificate from an authority on the C2PA trust list. A9 flagged that as
procurement with lead time. `SignedRender.trusted_chain` records which we had, so nothing
downstream can claim more than was actually proven.

Verified against the library on 2026-10-15: `c2pa-python` 0.38.0, MIT OR Apache-2.0,
signing `spike/runs/cut-v2/final_captioned.mp4` and reading it back as
`validation_state: Valid`.
"""

from __future__ import annotations

import datetime as dt
import json
import os
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Final

from app.pipeline.disclosure import FinalRender
from app.pipeline.errors import PipelineError

#: IPTC's term for media created by a model trained on sampled content — i.e. generative
#: AI output. Not a parameter. See the module docstring.
TRAINED_ALGORITHMIC_MEDIA: Final = (
    "http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia"
)

#: ES256 over P-256. The key must be PKCS#8 (`-----BEGIN PRIVATE KEY-----`); a SEC1 EC key
#: is refused by the library with an error about the PEM type label, which cost a round
#: trip to discover.
SIGNING_ALG: Final = "ES256"

#: Environment names. Values may be PEM text or a path to a PEM file — see `credentials`.
CERT_ENV: Final = "C2PA_SIGN_CERT"
KEY_ENV: Final = "C2PA_SIGN_KEY"

_MAKE_KEY = object()


class SigningFailed(PipelineError):
    """Signing could not be completed. Never swallowed: an unsigned render is not final."""


@dataclass(frozen=True)
class SigningCredentials:
    """A certificate chain and its private key, both as PEM bytes.

    The chain must be the end-entity certificate FIRST, then its issuer. A self-signed
    end-entity certificate on its own is refused by the library with "the certificate is
    invalid", which is accurate but unhelpful; the C2PA certificate profile wants a chain.
    """

    cert_chain_pem: bytes
    private_key_pem: bytes
    #: True only when the chain roots in an authority on the C2PA trust list. Ours does
    #: not yet, and saying so is the whole point of the field.
    trusted_chain: bool = False

    @property
    def is_self_signed(self) -> bool:
        return not self.trusted_chain


def credentials(
    cert: str | None = None, key: str | None = None, *, trusted: bool = False
) -> SigningCredentials:
    """Read signing credentials from the environment.

    Each value is either PEM text or a path to a PEM file, decided by whether it starts
    with a PEM header. Both are accepted because a certificate chain is multi-line and
    awkward in a shell, while the key is a secret that belongs in a secret store rather
    than on a disk somebody backs up.
    """
    raw_cert = cert if cert is not None else os.environ.get(CERT_ENV)
    raw_key = key if key is not None else os.environ.get(KEY_ENV)
    missing = [n for n, v in ((CERT_ENV, raw_cert), (KEY_ENV, raw_key)) if not v]
    if missing:
        raise SigningFailed(
            f"{' and '.join(missing)} not set, so nothing can be signed. Each is either "
            f"PEM text or a path to a PEM file. Generate a development pair with "
            f"`python -m scripts.make_signing_cert`; a manifest that verifies as TRUSTED "
            f"rather than self-signed needs a certificate from a recognised authority, "
            f"which is procurement with lead time (amendment A9)."
        )
    assert raw_cert is not None and raw_key is not None
    return SigningCredentials(
        cert_chain_pem=_pem_bytes(raw_cert, CERT_ENV),
        private_key_pem=_pem_bytes(raw_key, KEY_ENV),
        trusted_chain=trusted,
    )


def _pem_bytes(value: str, name: str) -> bytes:
    if value.lstrip().startswith("-----BEGIN"):
        return value.encode()
    path = Path(value)
    if not path.is_file():
        raise SigningFailed(f"{name} is neither PEM text nor a readable file: {value!r}")
    return path.read_bytes()


def build_manifest(
    *,
    title: str,
    generator: str,
    generator_version: str,
    persona_name: str | None = None,
    ingredients: list[str] | None = None,
    created: dt.datetime | None = None,
) -> dict[str, Any]:
    """The manifest to embed. Pure, so the shape is testable without the library.

    `ingredients` names the stages that produced the piece — the keyframe model, the video
    model, the voice — as free text. It is provenance for a human reading the manifest
    later, not a machine-checked chain, and saying so here is more honest than implying
    the latter.
    """
    when = (created or dt.datetime.now(dt.UTC)).isoformat()
    actions: list[dict[str, Any]] = [
        {
            "action": "c2pa.created",
            "when": when,
            "digitalSourceType": TRAINED_ALGORITHMIC_MEDIA,
            "softwareAgent": {"name": generator, "version": generator_version},
        }
    ]
    assertions: list[dict[str, Any]] = [
        {"label": "c2pa.actions", "data": {"actions": actions}},
        # Her likeness is the asset. Declaring that it may not be mined to train someone
        # else's model costs nothing and is the same position we take on our own inputs.
        {
            "label": "cawg.training-mining",
            "data": {
                "entries": {
                    "cawg.ai_inference": {"use": "notAllowed"},
                    "cawg.ai_generative_training": {"use": "notAllowed"},
                }
            },
        },
    ]
    if persona_name or ingredients:
        assertions.append(
            {
                "label": "stds.schema-org.CreativeWork",
                "data": {
                    "@context": "https://schema.org",
                    "@type": "CreativeWork",
                    **({"character": persona_name} if persona_name else {}),
                    **({"contributor": list(ingredients or [])} if ingredients else {}),
                },
            }
        )
    return {
        "claim_generator_info": [{"name": generator, "version": generator_version}],
        "title": title,
        "assertions": assertions,
    }


@dataclass(frozen=True)
class SignedRender:
    """A disclosed render that now carries a signed manifest.

    Constructed only by `sign`, for the same reason `FinalRender` is constructed only by
    `apply_disclosure`: holding one is the evidence, and a constructor anyone can call is
    evidence of nothing.
    """

    path: Path
    manifest: dict[str, Any]
    trusted_chain: bool
    _key: Any = None

    def __post_init__(self) -> None:
        if self._key is not _MAKE_KEY:
            raise SigningFailed(
                "SignedRender cannot be constructed directly. Call sign() — holding one "
                "is supposed to prove a manifest was embedded."
            )


def sign(
    render: FinalRender,
    dest: Path,
    *,
    creds: SigningCredentials,
    title: str,
    generator: str = "persona-studio",
    generator_version: str = "0.1.0",
    persona_name: str | None = None,
    ingredients: list[str] | None = None,
) -> SignedRender:
    """Embed a signed manifest in a disclosed render.

    Takes a `FinalRender` and nothing else, which is what makes "disclosure before
    signing" a property of the type system rather than a rule somebody has to remember.
    """
    # Imported here rather than at module scope so `make check` does not need the library
    # or a certificate: everything above this line is testable without either.
    from c2pa import Builder, C2paSignerInfo, C2paSigningAlg, Context, Signer

    if not render.path.is_file():
        raise SigningFailed(f"nothing to sign at {render.path}")
    manifest = build_manifest(
        title=title,
        generator=generator,
        generator_version=generator_version,
        persona_name=persona_name,
        ingredients=ingredients,
    )
    dest.parent.mkdir(parents=True, exist_ok=True)
    if dest.exists():
        # The library writes a new file and will not overwrite in place.
        dest.unlink()
    info = C2paSignerInfo(
        alg=C2paSigningAlg.ES256,
        sign_cert=creds.cert_chain_pem,
        private_key=creds.private_key_pem,
        ta_url=None,
    )
    try:
        with (
            Context() as context,
            Signer.from_info(info) as signer,
            Builder(json.dumps(manifest), context) as builder,
        ):
            builder.sign_file(str(render.path), str(dest), signer)
    except Exception as exc:
        raise SigningFailed(f"could not sign {render.path.name}: {exc}") from exc
    if not dest.is_file():
        raise SigningFailed(f"signing reported success but wrote nothing to {dest}")
    return SignedRender(
        path=dest, manifest=manifest, trusted_chain=creds.trusted_chain, _key=_MAKE_KEY
    )


def read_manifest(path: Path) -> dict[str, Any]:
    """Read back what a signed file claims, and whether it still validates.

    Returns the whole manifest store, including `validation_state`. A file that has been
    re-encoded — which is what platforms do on upload — will not have one at all, and
    that is expected rather than a fault.
    """
    from c2pa import Reader

    try:
        with Reader(str(path)) as reader:
            store: dict[str, Any] = json.loads(reader.json())
    except Exception as exc:
        raise SigningFailed(f"no readable manifest in {path.name}: {exc}") from exc
    return store
